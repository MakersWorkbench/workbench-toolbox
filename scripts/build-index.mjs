#!/usr/bin/env node
// Writes www/registry.js (tool list + tab names for search) and www/legal/NOTICES.txt.
// Tab names are read from the real tools in a headless browser, so they never drift from the vendored code.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { startServer } from './serve.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cfg = JSON.parse(readFileSync(join(ROOT, 'scripts/tools.config.json'), 'utf8'));
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));

function write(tabsById) {
  const tools = cfg.tools.map((t) => ({
    id: t.id, name: t.name, tagline: t.tagline, rootId: t.rootId, rootClass: t.rootClass, css: t.css,
    scripts: t.scripts, app: t.app, mountAttrs: t.mountAttrs || {}, tabs: tabsById[t.id] || [],
    repoUrl: `https://github.com/MakersWorkbench/${t.repo}`, wiki: `https://github.com/MakersWorkbench/${t.repo}/wiki`
  }));
  const reg = { version: pkg.version, tools };
  writeFileSync(join(ROOT, 'www/registry.js'), '/* Generated by scripts/build-index.mjs. Do not edit by hand. */\nwindow.TMWB_REGISTRY = ' + JSON.stringify(reg, null, 1) + ';\n');
}

let prev = {};
try { prev = Object.fromEntries(eval('(' + readFileSync(join(ROOT, 'www/registry.js'), 'utf8').replace(/^[\s\S]*?window\.TMWB_REGISTRY = /, '').replace(/;\s*$/, '') + ').tools').map((t) => [t.id, t.tabs])); } catch {}
write(prev);

const srv = await startServer(0);
const base = `http://127.0.0.1:${srv.address().port}/`;
const exe = existsSync('/opt/pw-browsers/chromium') ? '/opt/pw-browsers/chromium' : undefined;
const browser = await chromium.launch({ executablePath: exe });
const page = await browser.newPage();
const tabs = {};
for (const t of cfg.tools) {
  await page.goto(`${base}#/t/${t.id}`);
  await page.waitForSelector(`#${t.rootId} .tabbar button`);
  tabs[t.id] = await page.$$eval(`#${t.rootId} .tabbar button`, (bs) => bs.map((b) => b.textContent.trim()));
  console.log(t.id, tabs[t.id].length, 'tabs');
}
await browser.close(); srv.close();
write(tabs);

// Third-party notices: our own license, then each tool's NOTICE and SOURCES.md.
mkdirSync(join(ROOT, 'www/legal'), { recursive: true });
let out = 'WORKBENCH TOOLBOX\nCopyright 2026 TheMakersWorkbench.com. Licensed under the Apache License, Version 2.0.\nSee https://www.apache.org/licenses/LICENSE-2.0 for the full text. The LICENSE file in the source repository holds the same text.\nAffiliate links: none in this app.\n\n';
for (const t of cfg.tools) {
  out += '='.repeat(72) + `\n${t.name} (source: https://github.com/MakersWorkbench/${t.repo})\n` + '='.repeat(72) + '\n\n';
  for (const f of ['NOTICE', 'SOURCES.md']) {
    const p = join(ROOT, 'www/tools', t.id, f);
    if (existsSync(p)) out += `--- ${f} ---\n` + readFileSync(p, 'utf8').trim() + '\n\n';
  }
}
writeFileSync(join(ROOT, 'www/legal/NOTICES.txt'), out);
console.log('registry.js and legal/NOTICES.txt written');
