#!/usr/bin/env node
// Generates www/sw.js: a service worker that precaches every file in www/ so the app opens offline.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname, resolve, relative, sep } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const WWW = join(ROOT, 'www');
const SKIP = new Set(['sw.js']);
const files = [];
(function walk(d) {
  for (const n of readdirSync(d).sort()) {
    const p = join(d, n);
    if (statSync(p).isDirectory()) walk(p);
    else if (!SKIP.has(relative(WWW, p))) files.push(relative(WWW, p).split(sep).join('/'));
  }
})(WWW);
const hash = createHash('sha256');
for (const f of files) { hash.update(f); hash.update(readFileSync(join(WWW, f))); }
const version = hash.digest('hex').slice(0, 12);
const sw = `/* Generated by scripts/build-sw.mjs. Do not edit by hand. */
const CACHE = 'tmwb-toolbox-${version}';
const FILES = ${JSON.stringify(['./'].concat(files), null, 1)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => new Request(f, { cache: 'reload' })))));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('tmwb-toolbox-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('message', (e) => { if (e.data === 'SKIP_WAITING') self.skipWaiting(); });
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== self.location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || (e.request.mode === 'navigate' ? caches.match('./index.html') : null) || fetch(e.request)));
});
`;
if (process.argv.includes('--check')) {
  let cur = ''; try { cur = readFileSync(join(WWW, 'sw.js'), 'utf8'); } catch {}
  if (cur !== sw) { console.error('www/sw.js is out of date. Run: npm run build:sw'); process.exit(1); }
  console.log('sw.js is up to date'); process.exit(0);
}
writeFileSync(join(WWW, 'sw.js'), sw);
console.log(`sw.js written: ${files.length} files precached, cache tmwb-toolbox-${version}`);
